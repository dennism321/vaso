export function getTeam(locale: Locale) {
  if (locale === "el") return team;
  return team.map((member, i) => ({
    ...member,
    role: teamEn[i]?.role ?? member.role,
    focus: teamEn[i]?.focus ?? member.focus,
    bio: teamEn[i]?.bio ?? member.bio,
  }));
}

